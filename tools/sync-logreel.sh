#!/usr/bin/env bash
# Copy the logreel workspace into this repository.
#
# The library lives in its own repository, https://github.com/Kraionix/logreel.
# A pinned copy is checked in so every build reads the same bytes and a clean
# checkout needs no clone. This script is the only way that copy is produced:
# run it after checking out the logreel commit VENDORED.md names, run it again
# to prove the copy still matches.
#
# Usage: tools/sync-logreel.sh [path-to-logreel-repo]
#
# Two patches are applied to the upstream tree, recorded in VENDORED.md: the
# facade's optional redb backend and the derive macro are removed, because
# neither is vendored and the proxy must not be able to resolve code it never
# links.
set -euo pipefail

repo=$(cd "$(dirname "$0")/.." && pwd)
src=${1:-$repo/../logreel}
dest=$repo/vendor/logreel
crates=(logreel logreel-core logreel-store logreel-file)

if [ ! -f "$src/Cargo.toml" ] || [ ! -d "$src/crates/logreel-core" ]; then
    echo "sync-logreel: $src does not look like the logreel workspace" >&2
    exit 1
fi

version=$(sed -n 's/^version = "\(.*\)"$/\1/p' "$src/Cargo.toml" | head -n 1)
commit=$(git -C "$src" rev-parse HEAD)
tree=$(git -C "$src" rev-parse 'HEAD^{tree}')

rm -rf "$dest"
mkdir -p "$dest/crates"
for crate in "${crates[@]}"; do
    cp -R "$src/crates/$crate" "$dest/crates/$crate"
done
cp "$src/LICENSE" "$dest/LICENSE"
# The file crate's conformance tests read the fixture segments, which live at
# the workspace root; without them the vendored workspace's test job fails.
cp -R "$src/fixtures" "$dest/fixtures"
find "$dest" -name target -type d -prune -exec rm -rf {} +

# Patch 1: no redb backend.
sed -i '/^redb = \["dep:logreel-store-redb"\]$/d' "$dest/crates/logreel/Cargo.toml"
sed -i '/^logreel-store-redb = { workspace = true, optional = true }$/d' "$dest/crates/logreel/Cargo.toml"
sed -i '/^\/\/\/ Optional redb backend\.$/d' "$dest/crates/logreel/src/lib.rs"
sed -i '/^#\[cfg(feature = "redb")\]$/d' "$dest/crates/logreel/src/lib.rs"
sed -i '/^pub use logreel_store_redb as redb;$/d' "$dest/crates/logreel/src/lib.rs"
sed -i 's/Enable file, zstd or redb/Enable file or zstd/' "$dest/crates/logreel/src/lib.rs"
# The facade has a conformance test for each backend, guarded by that backend's
# feature. Removing the feature leaves a test that never compiles and a rustc
# warning about an undeclared `redb` feature, so the test goes with it.
sed -i 's/^#!\[cfg(any(feature = "file", feature = "redb"))\]$/#![cfg(feature = "file")]/' "$dest/crates/logreel/tests/facade.rs"
sed -i '/^#\[cfg(feature = "redb")\]$/,/^}$/d' "$dest/crates/logreel/tests/facade.rs"
sed -i -e :a -e '/^\n*$/{$d;N;ba' -e '}' "$dest/crates/logreel/tests/facade.rs"
# Patch 2: no derive macro.
#
# The proxy implements `logreel::Event` by hand over its prost schema: the
# enum is a prost oneof whose tags are the event numbers, and the derive would
# need every one of the 22 artifact messages to carry a second derive and its
# own kind attribute, duplicating the numbers the schema already fixes.
# Vendoring the macro would only put syn, quote and proc-macro2 in the build.
sed -i '/^logreel-derive\.workspace = true$/d' "$dest/crates/logreel/Cargo.toml"
sed -i '/^logreel-derive = { workspace = true }$/d' "$dest/crates/logreel/Cargo.toml"
sed -i '/^pub use logreel_derive::Event;$/d' "$dest/crates/logreel/src/lib.rs"
sed -i 's/logreel-core, the derive macro, and the optional segment file backend/logreel-core and the optional segment file backend/' "$dest/crates/logreel/src/lib.rs"

# The three deleted lines left the file ending in a blank line, which rustfmt
# --check rejects; strip it so the vendored tree formats exactly as upstream.
sed -i -e :a -e '/^\n*$/{$d;N;ba' -e '}' "$dest/crates/logreel/src/lib.rs"

cat > "$dest/Cargo.toml" <<EOF
# Vendored copy of the logreel workspace. Generated by tools/sync-logreel.sh;
# do not edit. See VENDORED.md for the source commit and the patch list.
[workspace]
resolver = "3"
members = [
    "crates/logreel",
    "crates/logreel-core",
    "crates/logreel-store",
    "crates/logreel-file",
]

[workspace.package]
version = "$version"
edition = "2024"
rust-version = "1.98"
license = "MIT"
repository = "https://github.com/Kraionix/logreel"
authors = ["logreel contributors"]

[workspace.dependencies]
logreel-core = { path = "crates/logreel-core", version = "=$version" }
logreel-store = { path = "crates/logreel-store", version = "=$version" }
logreel-file = { path = "crates/logreel-file", version = "=$version" }
logreel = { path = "crates/logreel", version = "=$version" }

tokio = { version = "1.53", default-features = false, features = ["rt"] }
zstd = "0.14"
serde_json = "1.0.154"

[workspace.lints.rust]
unsafe_code = "forbid"
missing_docs = "warn"
missing_debug_implementations = "warn"
unreachable_pub = "warn"
rust_2018_idioms = { level = "warn", priority = -1 }

[workspace.lints.clippy]
all = { level = "warn", priority = -1 }
doc_markdown = "allow"
module_name_repetitions = "allow"
must_use_candidate = "allow"
cast_possible_truncation = "allow"
cast_sign_loss = "allow"
cast_possible_wrap = "allow"
missing_errors_doc = "allow"
missing_panics_doc = "allow"
too_many_lines = "allow"
EOF

cat > "$dest/VENDORED.md" <<'EOF'
# Vendored logreel

Generated by `tools/sync-logreel.sh`; do not edit by hand. To refresh, check
out the source commit below in [logreel](https://github.com/Kraionix/logreel) and run:

```
tools/sync-logreel.sh ../logreel
```

| item | value |
|---|---|
| source commit | `@COMMIT@` |
| source tree | `@TREE@` |
| version | `@VERSION@` |
| crates | `logreel`, `logreel-core`, `logreel-store`, `logreel-file` |
| fixtures | `fixtures/` (the file crate's conformance corpus) |
| specification | `docs/SPEC.md` and `docs/FORMAT.md` are not copied; the format documents stay in the [logreel repository](https://github.com/Kraionix/logreel/tree/main/docs) |

## Patches

1. **No redb backend.** `logreel-store-redb` is not vendored: its optional
   dependency, its `redb` feature and the facade's re-export of it are removed,
   and so is the facade test that opens that backend.
   The proxy writes segments and has no use for a second storage engine, and a
   dependency the build can resolve but never use is one a rebuild may
   accidentally link.
2. **No derive macro.** `logreel-derive` and its `logreel` re-export are
   not vendored. The proxy implements `logreel::Event` by hand for its prost
   oneof: the derive would require a second derive and a kind attribute on each
   of the 22 schema messages, duplicating the tags the schema fixes. Vendoring
   it would put `syn`, `quote` and `proc-macro2` in every build for a macro
   this tree never expands.

Nothing else differs from the source tree; `git diff` against the upstream
commit is the check.
EOF

sed -i "s/@COMMIT@/$commit/; s/@TREE@/$tree/; s/@VERSION@/$version/" "$dest/VENDORED.md"

echo "vendored logreel $version at $commit into $dest"
